// Run against the exact packaged or live page:
// node scripts/verify-video-demo-browser.mjs <URL> <private evidence directory>
// CHROME_PATH may override the system Chrome executable; no browser install is needed.
import assert from "node:assert/strict"
import { mkdirSync, writeFileSync } from "node:fs"
import { resolve } from "node:path"
import { chromium } from "playwright-core"

const [url, directory] = process.argv.slice(2)
if (!url || !directory) throw new Error("Pass the packaged/live URL and a private evidence directory")
const out = resolve(directory)
mkdirSync(out, { recursive: true })
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH ?? "/usr/bin/google-chrome", headless: true, args: ["--mute-audio", "--no-sandbox"] })
const checks = []
const check = (name) => { checks.push(name); console.log(`PASS ${name}`) }
const failures = []
const context = await browser.newContext({ viewport: { width: 1280, height: 1000 } })
const page = await context.newPage()
page.on("pageerror", (error) => failures.push(String(error)))
try {
  await page.goto(url)
  const stage = page.locator(".video-demo .stage-wrap")
  await stage.scrollIntoViewIfNeeded()
  await page.getByRole("button", { name: "Play with sound", exact: true }).waitFor()
  assert.equal(await page.locator("video").count(), 1)
  assert.equal(await page.locator("video").getAttribute("preload"), "none")
  assert.equal(await page.evaluate(() => performance.getEntriesByType("resource").filter((entry) => entry.name.includes(".mp4")).length), 0)
  check("poster is visible without downloading the movie")
  await page.screenshot({ path: `${out}/desktop-poster.png` })
  const chapters = [["Start", 0], ["Capture", 3.7333333333333334], ["Sketch", 15.433333333333334], ["Handoff", 27.92], ["Result", 48.7], ["Try it", 55.7]]
  // Seek before metadata has loaded, without first starting at zero.
  await page.getByRole("button", { name: "Chapter: Result", exact: true }).click()
  await page.waitForFunction(() => { const v = document.querySelector("video"); return v.readyState >= 2 && !v.paused && v.currentTime >= 48.7 && v.currentTime < 50 })
  await page.getByRole("button", { name: "Pause", exact: true }).click()
  check("a chapter works on first load, before metadata is available")
  await page.reload()
  await page.getByRole("button", { name: "Play with sound", exact: true }).click()
  await page.waitForFunction(() => { const v = document.querySelector("video"); return v.currentTime > .1 && !v.paused && !v.muted })
  check("Play with sound starts the real video with sound enabled")
  await page.getByRole("button", { name: "Pause", exact: true }).click()
  const paused = await page.locator("video").evaluate((v) => v.currentTime)
  await page.waitForTimeout(250)
  assert.equal(await page.locator("video").evaluate((v) => v.paused), true)
  assert.ok(Math.abs(await page.locator("video").evaluate((v) => v.currentTime) - paused) < .1)
  check("Pause stops playback")
  await page.getByRole("button", { name: "Mute sound", exact: true }).click()
  assert.equal(await page.locator("video").evaluate((v) => v.muted), true)
  await page.getByRole("button", { name: "Enable sound", exact: true }).click()
  assert.equal(await page.locator("video").evaluate((v) => v.muted), false)
  check("the sound toggle controls the video audio")
  for (const [name, time] of chapters) {
    const button = page.getByRole("button", { name: `Chapter: ${name}`, exact: true })
    await button.click()
    await page.waitForFunction((seconds) => { const v = document.querySelector("video"); return !v.paused && !v.seeking && v.currentTime >= seconds && v.currentTime < seconds + 1 }, time)
    await page.getByRole("button", { name: "Pause", exact: true }).click()
    await page.getByRole("button", { name: "Play", exact: true }).waitFor()
    await page.waitForFunction((name) => document.querySelector(`button[aria-label="Chapter: ${name}"]`)?.getAttribute("aria-current") === "step", name)
    assert.ok(Math.abs(await page.locator("video").evaluate((v) => v.currentTime) - time) < 1)
    await page.screenshot({ path: `${out}/chapter-${name.replaceAll(" ", "-")}.png` })
    check(`chapter ${name} seeks to ${time.toFixed(3)}s and updates the active chapter`)
  }
  await page.getByRole("button", { name: "Replay", exact: true }).first().click()
  await page.waitForFunction(() => { const v = document.querySelector("video"); return !v.paused && v.currentTime < 1 })
  check("Replay returns to the beginning and plays")
  const slider = page.getByRole("slider", { name: "Demo timeline" })
  const bounds = await slider.boundingBox()
  await page.mouse.move(bounds.x + bounds.width * .25, bounds.y + bounds.height / 2)
  await page.mouse.down()
  await page.mouse.move(bounds.x + bounds.width * .6, bounds.y + bounds.height / 2, { steps: 5 })
  await page.mouse.up()
  await page.waitForFunction(() => { const v = document.querySelector("video"); return v.paused && !v.seeking && Math.abs(v.currentTime - v.duration * .6) < .3 })
  check("pointer scrubbing seeks the video and leaves it paused")
  await slider.focus()
  await page.keyboard.press("Home")
  await page.waitForFunction(() => document.querySelector("video").currentTime < .1)
  await page.keyboard.press("ArrowRight")
  await page.waitForFunction(() => Math.abs(document.querySelector("video").currentTime - 5) < .1)
  check("the focused timeline responds to Home and ArrowRight")
  await stage.focus()
  await page.keyboard.press("Space")
  await page.waitForFunction(() => !document.querySelector("video").paused)
  await page.keyboard.press("Space")
  await page.waitForFunction(() => document.querySelector("video").paused)
  check("stage Space toggles play and pause")
  assert.equal(await page.getByRole("button", { name: "Draw on demo", exact: true }).count(), 0)
  const drawing = await stage.boundingBox()
  await page.keyboard.down("Shift")
  await page.mouse.move(drawing.x + drawing.width * .3, drawing.y + drawing.height * .3)
  await page.mouse.down()
  await page.mouse.move(drawing.x + drawing.width * .6, drawing.y + drawing.height * .4, { steps: 10 })
  await page.mouse.up()
  await page.keyboard.up("Shift")
  assert.equal(await page.locator(".video-demo-ink").count(), 0)
  assert.equal(await stage.evaluate((el) => el.classList.contains("drawing")), false)
  check("drawing controls and the Shift-drag ink overlay are absent")
  // Real end-of-media event, not a synthetic ended event.
  await slider.focus()
  await page.keyboard.press("End")
  await page.getByRole("button", { name: "Play", exact: true }).click()
  await page.waitForFunction(() => { const v = document.querySelector("video"); return !v.paused && v.currentTime < 1 })
  await page.locator("video").evaluate((v) => { v.currentTime = v.duration - .15 })
  await page.waitForFunction(() => document.querySelector("video").ended)
  await page.locator(".stage-end").getByRole("button", { name: "Replay", exact: true }).click()
  await page.waitForFunction(() => { const v = document.querySelector("video"); return !v.paused && v.currentTime < 1 })
  check("natural ending exposes Replay and Replay restarts the movie")
  await page.getByRole("button", { name: "Pause", exact: true }).click()
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 })
    await page.reload()
    await stage.scrollIntoViewIfNeeded()
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    for (const [name, time] of chapters) {
      await page.getByRole("button", { name: `Chapter: ${name}`, exact: true }).click()
      await page.waitForFunction((time) => { const v = document.querySelector("video"); return !v.paused && v.currentTime >= time - .001 && v.currentTime < time + 1 }, time)
      await page.getByRole("button", { name: "Pause", exact: true }).click()
      await page.getByRole("button", { name: "Play", exact: true }).waitFor()
    }
    await page.locator(".controls").scrollIntoViewIfNeeded()
    assert.equal(await page.locator('.controls button, .controls [role="slider"]').evaluateAll((elements) => elements.every((el) => {
      const r = el.getBoundingClientRect()
      return r.width > 0 && r.height > 0 && r.left >= 0 && r.right <= innerWidth && r.top >= 0 && r.bottom <= innerHeight && el.contains(document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2))
    })), true, "every control is visible, inside the viewport and independently hit-testable")
    await page.screenshot({ path: `${out}/mobile-${width}.png` })
    check(`all controls fit and chapters work at ${width}px`)
  }
  await page.reload()
  await page.getByRole("button", { name: "Chapter: Sketch", exact: true }).click()
  await page.getByRole("button", { name: "Pause", exact: true }).click()
  await page.waitForFunction(() => document.querySelector("video").paused)
  await page.getByRole("button", { name: "Chapter: Result", exact: true }).click()
  await page.waitForFunction(() => { const v = document.querySelector("video"); return !v.paused && v.currentTime >= 48.7 && v.currentTime < 50 })
  check("rapid pause and chapter switching do not strand playback")
  let releaseMedia
  const mediaGate = new Promise((resolve) => { releaseMedia = resolve })
  await page.route("**/Apparent-ghost-demo-v4-lilac.mp4", async (route) => { await mediaGate; await route.continue() })
  await page.reload({ waitUntil: "domcontentloaded" })
  await page.getByRole("button", { name: "Chapter: Sketch", exact: true }).click()
  await page.waitForFunction(() => document.querySelector("video").readyState === 0 && !document.querySelector("video").paused)
  await page.getByRole("button", { name: "Pause", exact: true }).click()
  await page.getByRole("button", { name: "Chapter: Result", exact: true }).click()
  releaseMedia()
  await page.waitForFunction(() => { const v = document.querySelector("video"); return !v.paused && v.currentTime >= 48.7 && v.currentTime < 50 })
  await page.unroute("**/Apparent-ghost-demo-v4-lilac.mp4")
  check("delayed first-load metadata preserves the latest chapter after pause and switching")
  assert.deepEqual(failures, [], "no browser runtime errors")
  check("no browser runtime errors")
  const unavailable = await context.newPage()
  await unavailable.route("**/Apparent-ghost-demo-v4-lilac.mp4", (route) => route.abort("failed"))
  await unavailable.goto(url)
  await unavailable.getByRole("button", { name: "Play with sound", exact: true }).click()
  await unavailable.getByRole("alert").waitFor()
  assert.equal(await unavailable.getByRole("link", { name: "Open video", exact: true }).getAttribute("href"), "/Apparent-ghost-demo-v4-lilac.mp4")
  check("media failures show an honest visible error and direct-video fallback")
  writeFileSync(`${out}/results.json`, JSON.stringify({ url, checks, runtimeErrors: failures }, null, 2) + "\n")
} finally {
  await browser.close()
}
