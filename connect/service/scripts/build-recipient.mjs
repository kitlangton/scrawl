import { build } from 'esbuild'
import { execFileSync } from 'node:child_process'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
const root = fileURLToPath(new URL('../', import.meta.url))
await mkdir(root + '.generated', { recursive: true })
const client = await build({ entryPoints: [root + 'src/recipient/client.tsx'], bundle: true, format: 'iife', platform: 'browser', minify: true, write: false, define: { 'process.env.NODE_ENV': '"production"' } })
execFileSync(root + 'node_modules/.bin/tailwindcss', ['-i', 'src/recipient/styles.css', '-o', '.generated/recipient.css', '--minify'], { cwd: root, stdio: 'inherit' })
const [styles, wordmark, font] = await Promise.all([
  readFile(root + '.generated/recipient.css', 'utf8'),
  readFile(root + '../../shared/assets/brand/apparent-wordmark.svg', 'utf8'),
  readFile(root + '../../shared/assets/fonts/HostGrotesk-Variable.ttf'),
])
await writeFile(root + '.generated/recipient-assets.ts', `// Generated by scripts/build-recipient.mjs; do not edit.\nexport const shareViewScript=${JSON.stringify(client.outputFiles[0].text)};\nexport const shareViewStyles=${JSON.stringify(styles)};\nexport const shareWordmark=${JSON.stringify(wordmark)};\nexport const shareFont=${JSON.stringify(font.toString('base64'))};\n`)

await build({ entryPoints: [root + 'src/recipient/render.tsx'], bundle: true, format: 'esm', platform: 'browser', conditions: ['workerd'], minify: true, outfile: root + '.generated/recipient-render.js', define: { 'process.env.NODE_ENV': JSON.stringify('production') } })
await writeFile(root + '.generated/recipient-render.d.ts', "export { renderShare } from '../src/recipient/render.tsx'\n")
